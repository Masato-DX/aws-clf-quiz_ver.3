/**
 * 問題ファクトリ。
 * module を引数で受け取ることで、配列インデックス依存の紐付けを排除している。
 *
 * @param {number} id          一意の連番
 * @param {string} domain      DOMAINS のキー
 * @param {string} module      MODULES のキー（公式テキストの章）
 * @param {string} diff        beginner / intermediate / advanced
 * @param {string} q           問題文
 * @param {string[]} opts      選択肢
 * @param {number|number[]} ans 正解インデックス（複数選択は配列）
 * @param {string} exp         解説
 */
export const Q = (id, domain, module, diff, q, opts, ans, exp) => {
  const correctAnswers = (Array.isArray(ans) ? ans : [ans]).slice().sort((a, b) => a - b);
  return {
    id,
    domain,
    module,
    difficulty: diff,
    question: q,
    options: opts,
    correctAnswers,
    multiSelect: correctAnswers.length > 1,
    explanation: exp,
  };
};

